-- ------------------------------------------------- helper (anti-rekursi RLS)
-- Policy yang query tabel profiles dari dalam policy profiles (atau via
-- rantai policy tabel lain -> profiles) menyebabkan "infinite recursion".
-- Semua cek role lecturer WAJIB lewat fungsi SECURITY DEFINER ini
-- (bypass RLS, baca role milik penelepon sendiri saja).
CREATE OR REPLACE FUNCTION public.is_lecturer()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'LECTURER'
  );
$$;
GRANT EXECUTE ON FUNCTION public.is_lecturer() TO authenticated;

-- ----------------------------------------------------------------- policies
-- 1. profiles: select own.
CREATE POLICY profiles_select_own
  ON public.profiles FOR SELECT TO authenticated
  USING (auth.uid() = id);

-- 2. profiles: lecturer boleh baca semua profil (students yang enrolled
--    di-derive dari enrollments; schedules hanya menyimpan lecturer_name
--    text sehingga tidak ada FK lecturer -> schedule).
CREATE POLICY profiles_lecturer_read
  ON public.profiles FOR SELECT TO authenticated
  USING (public.is_lecturer());

-- 3. schedules: select jika enrolled di jadwal itu, atau lecturer.
CREATE POLICY schedules_select_enrolled_or_lecturer
  ON public.schedules FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.schedule_id = schedules.id AND e.student_id = auth.uid()
    )
    OR public.is_lecturer()
  );

-- 4. enrollments: select own + lecturer. (Tidak ada di daftar brief, tapi
--    WAJIB ada: policy schedules/qr_tokens/codes memakai EXISTS ke tabel
--    ini, dan tanpa policy hasilnya selalu kosong karena RLS default-deny.)
CREATE POLICY enrollments_select_own_or_lecturer
  ON public.enrollments FOR SELECT TO authenticated
  USING (
    student_id = auth.uid()
    OR public.is_lecturer()
  );

-- 5. attendance_records: select own (inti check Task 1: student A tidak
--    bisa baca milik student B).
CREATE POLICY attendance_records_select_own
  ON public.attendance_records FOR SELECT TO authenticated
  USING (student_id = auth.uid());

-- 6. attendance_records: lecturer baca semua record.
CREATE POLICY attendance_records_lecturer_select
  ON public.attendance_records FOR SELECT TO authenticated
  USING (public.is_lecturer());

-- 7. attendance_records: TIDAK ada direct insert. Insert hanya lewat
--    fungsi RPC SECURITY DEFINER (dibuat di task berikutnya); policy
--    deny-eksplisit ini membuat intent tersebut terlihat di katalog.
CREATE POLICY attendance_records_no_direct_insert
  ON public.attendance_records FOR INSERT TO authenticated
  WITH CHECK (false);

-- 8. qr_tokens: select jika enrolled, tanpa direct insert (tanpa policy INSERT).
CREATE POLICY qr_tokens_select_enrolled
  ON public.qr_tokens FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.schedule_id = qr_tokens.schedule_id AND e.student_id = auth.uid()
    )
    OR public.is_lecturer()
  );

-- 9. attendance_codes: select jika enrolled, tanpa direct insert.
CREATE POLICY attendance_codes_select_enrolled
  ON public.attendance_codes FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.schedule_id = attendance_codes.schedule_id AND e.student_id = auth.uid()
    )
    OR public.is_lecturer()
  );

-- 10. permit_requests: select own.
CREATE POLICY permit_requests_select_own
  ON public.permit_requests FOR SELECT TO authenticated
  USING (student_id = auth.uid());

-- 11. permit_requests: insert own.
CREATE POLICY permit_requests_insert_own
  ON public.permit_requests FOR INSERT TO authenticated
  WITH CHECK (student_id = auth.uid());

