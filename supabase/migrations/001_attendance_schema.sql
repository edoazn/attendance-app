-- ------------------------------------------------- view jadwal hari ini
CREATE OR REPLACE VIEW public.today_schedules_with_flags AS
SELECT
  s.*,
  EXISTS (
    SELECT 1 FROM public.qr_tokens q
    WHERE q.schedule_id = s.id AND q.expires_at > now()
  ) AS has_qr,
  EXISTS (
    SELECT 1 FROM public.attendance_codes c
    WHERE c.schedule_id = s.id AND c.is_active = true AND c.expires_at > now()
  ) AS has_active_code
FROM public.schedules s
WHERE s.day = TRIM(TO_CHAR(now(), 'Day'))
  AND s.is_active = true;

GRANT SELECT ON public.today_schedules_with_flags TO authenticated;
