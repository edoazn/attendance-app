-- ---------------------------------------------------------------- profiles
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  identity_number text UNIQUE NOT NULL,
  name text NOT NULL,
  email text,
  role text NOT NULL CHECK (role IN ('STUDENT', 'LECTURER'))
);

-- ---------------------------------------------------------------- schedules
CREATE TABLE IF NOT EXISTS public.schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_name text NOT NULL,
  lecturer_name text,
  room text,
  day text NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  -- R1 (tambahan di luar brief, wajib): ambang keterlambatan + geofence kelas.
  late_threshold_minutes integer NOT NULL DEFAULT 15,
  latitude double precision,
  longitude double precision,
  radius_meters integer NOT NULL DEFAULT 100
);

-- -------------------------------------------------------------- enrollments
CREATE TABLE IF NOT EXISTS public.enrollments (
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  PRIMARY KEY (schedule_id, student_id)
);

-- ---------------------------------------------------------------- qr_tokens
CREATE TABLE IF NOT EXISTS public.qr_tokens (
  token uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);

-- ---------------------------------------------------------- attendance_codes
CREATE TABLE IF NOT EXISTS public.attendance_codes (
  code char(6) PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);

-- ------------------------------------------------------- attendance_records
CREATE TABLE IF NOT EXISTS public.attendance_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  method text,
  status text,
  distance double precision,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (schedule_id, student_id)
);

-- ------------------------------------------------------------ permit_requests
CREATE TABLE IF NOT EXISTS public.permit_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  alasan text,
  created_at timestamptz NOT NULL DEFAULT now()
);

