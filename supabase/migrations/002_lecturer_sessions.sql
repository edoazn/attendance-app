-- ------------------------------------------------- schedules: kolom sesi
ALTER TABLE public.schedules
  ADD COLUMN IF NOT EXISTS lecturer_id uuid REFERENCES public.profiles (id) ON DELETE SET NULL;
ALTER TABLE public.schedules
  ADD COLUMN IF NOT EXISTS session_open boolean NOT NULL DEFAULT false;
ALTER TABLE public.schedules
  ADD COLUMN IF NOT EXISTS session_expires_at timestamptz;

-- Backfill kondisional: hanya bila lecturer_name cocok profil dosen yang
-- ada (guard implisit — baris tanpa nama cocok tetap NULL = pool
-- unassigned). Tanpa UUID hardcode.
UPDATE public.schedules s
SET lecturer_id = p.id
FROM public.profiles p
WHERE p.role = 'LECTURER'
  AND p.name = s.lecturer_name
  AND s.lecturer_id IS NULL;

-- ------------------------------------------------- qr_tokens: statis unik
-- Dedupe defensif: pola lama (generate-session) membuat banyak baris per
-- jadwal. Pertahankan satu baris per jadwal (expiry terbaru = sesi
-- terakhir), sisanya dibuang sebelum UNIQUE dipasang.
DELETE FROM public.qr_tokens q
USING public.qr_tokens newer
WHERE newer.schedule_id = q.schedule_id
  AND newer.expires_at > q.expires_at;
-- Bila expiry identik (seri), sisakan satu baris arbitrer per jadwal.
DELETE FROM public.qr_tokens q
WHERE EXISTS (
  SELECT 1 FROM public.qr_tokens other
  WHERE other.schedule_id = q.schedule_id
    AND other.token > q.token
);
ALTER TABLE public.qr_tokens
  ADD CONSTRAINT qr_tokens_schedule_id_unique UNIQUE (schedule_id);

-- ------------------------------------------------- attendance_sessions
CREATE TABLE IF NOT EXISTS public.attendance_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES public.schedules (id) ON DELETE CASCADE,
  opened_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz NULL
);
ALTER TABLE public.attendance_sessions ENABLE ROW LEVEL SECURITY;

-- ------------------------------------------------- attendance_records: sesi
ALTER TABLE public.attendance_records
  ADD COLUMN IF NOT EXISTS session_id bigint REFERENCES public.attendance_sessions (id) ON DELETE CASCADE;

-- Buang UNIQUE lama (schedule_id, student_id): dicari dinamis lewat katalog
-- agar tidak bergantung pada nama constraint bawaan Postgres.
DO $$
DECLARE cname text;
BEGIN
  SELECT c.conname INTO cname
  FROM pg_constraint c
  JOIN pg_class t ON t.oid = c.conrelid
  JOIN pg_namespace ns ON ns.oid = t.relnamespace
  WHERE ns.nspname = 'public'
    AND t.relname = 'attendance_records'
    AND c.contype = 'u'
    AND (SELECT array_agg(a.attname::text ORDER BY k.ord)
         FROM unnest(c.conkey) WITH ORDINALITY AS k(attnum, ord)
         JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum)
        = ARRAY['schedule_id', 'student_id'];
  IF cname IS NOT NULL THEN
    EXECUTE format(
      'ALTER TABLE public.attendance_records DROP CONSTRAINT %I', cname);
  END IF;
END $$;

ALTER TABLE public.attendance_records
  ADD CONSTRAINT attendance_records_session_student_unique
  UNIQUE (session_id, student_id);

