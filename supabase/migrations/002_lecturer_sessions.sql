-- ------------------------------------------------------------------- RLS
-- Persempit policy lecturer: hanya jadwal miliknya + pool unassigned
-- (lecturer_id IS NULL). Nama policy dipertahankan agar katalog lama stabil.
DROP POLICY IF EXISTS schedules_select_enrolled_or_lecturer ON public.schedules;
CREATE POLICY schedules_select_enrolled_or_lecturer
  ON public.schedules FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.schedule_id = schedules.id AND e.student_id = auth.uid()
    )
    OR (
      public.is_lecturer()
      AND (schedules.lecturer_id = auth.uid() OR schedules.lecturer_id IS NULL)
    )
  );

-- attendance_sessions: select ikut induk (enrolled / lecturer own+pool).
CREATE POLICY attendance_sessions_select_via_schedule
  ON public.attendance_sessions FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.schedule_id = attendance_sessions.schedule_id
        AND e.student_id = auth.uid()
    )
    OR (
      public.is_lecturer()
      AND EXISTS (
        SELECT 1 FROM public.schedules s
        WHERE s.id = attendance_sessions.schedule_id
          AND (s.lecturer_id = auth.uid() OR s.lecturer_id IS NULL)
      )
    )
  );

